create temporary table rating_cleanup_before on commit drop as
  select id, to_jsonb(d) as snapshot from public.atlanta_drivers d;

do $$
begin
  if (select count(*) from rating_cleanup_plan) <> 390 then raise exception 'Unexpected plan size'; end if;
  if exists(select 1 from rating_cleanup_plan p left join public.atlanta_drivers d on d.id=p.driver_id
    where d.id is null or d.location is distinct from p.location or d."Driver Rating" is distinct from p.old_rating) then
    raise exception 'A planned driver changed since review; regenerate the plan before applying';
  end if;
  if exists(select 1 from public.atlanta_drivers d join public.atlanta_drivers seed on seed.profile_key=d.profile_key
    join rating_cleanup_plan p on p.driver_id=seed.id where d.location not in ('atlanta','preferred')
    or not exists(select 1 from rating_cleanup_plan target where target.driver_id=d.id)) then
    raise exception 'A shared profile has an unreviewed membership';
  end if;
  if exists(select d.profile_key from public.atlanta_drivers d join rating_cleanup_plan p on p.driver_id=d.id
    group by d.profile_key having count(distinct coalesce(p.new_rating,'<unrated>'))<>1) then
    raise exception 'Conflicting ratings within a shared profile';
  end if;
end;
$$;

-- Preserve complete before-images privately; only Driver Rating is changed.
insert into private.driver_profile_sync_backups(migration_name,driver_id,snapshot)
  select 'atlanta_preferred_rating_cleanup_20261015',b.id,
    b.snapshot || jsonb_build_object('_rating_cleanup',jsonb_build_object('new_rating',p.new_rating))
  from rating_cleanup_before b join rating_cleanup_plan p on p.driver_id=b.id;

-- Update one representative per profile. Its existing sync trigger updates
-- peers. Updating all peers directly in the same command can cause a tuple-
-- already-modified error and must not be used here.
with representatives as (
  select distinct on (d.profile_key) d.id,p.new_rating
  from public.atlanta_drivers d join rating_cleanup_plan p on p.driver_id=d.id
  order by d.profile_key,d.id
)
update public.atlanta_drivers d set "Driver Rating"=r.new_rating
from representatives r where d.id=r.id;

do $$
begin
  if exists(select 1 from rating_cleanup_plan p join public.atlanta_drivers d on d.id=p.driver_id
    where d."Driver Rating" is distinct from p.new_rating) then raise exception 'Not every planned rating was applied'; end if;
  if exists(select 1 from rating_cleanup_before b full join public.atlanta_drivers d on d.id=b.id
    where b.id is null or d.id is null or
      (to_jsonb(d)-'Driver Rating') is distinct from (b.snapshot-'Driver Rating')) then
    raise exception 'A non-rating field or list membership changed';
  end if;
  if exists(select 1 from rating_cleanup_before b join public.atlanta_drivers d on d.id=b.id
    where not exists(select 1 from rating_cleanup_plan p where p.driver_id=d.id)
      and to_jsonb(d) is distinct from b.snapshot) then raise exception 'An unplanned profile changed'; end if;
end;
$$;
