create table if not exists public.archive_backup_runs (
  id uuid primary key default extensions.gen_random_uuid(),
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  status text not null default 'running'
    check (status in ('running','success','partial','failed','disabled','configuration_required')),
  files_considered integer not null default 0,
  files_archived integer not null default 0,
  files_deleted integer not null default 0,
  bytes_archived bigint not null default 0,
  bytes_downloaded bigint not null default 0,
  error_message text,
  destination_label text,
  details jsonb not null default '{}'::jsonb
);

create table if not exists public.archive_backup_items (
  id bigint generated by default as identity primary key,
  bucket_id text not null,
  object_name text not null,
  source_object_id uuid,
  source_created_at timestamptz,
  source_bytes bigint not null default 0,
  provider text not null default 'onedrive',
  provider_drive_id text,
  provider_item_id text,
  provider_web_url text,
  provider_path text,
  provider_size bigint,
  archived_at timestamptz,
  source_deleted_at timestamptz,
  status text not null default 'pending' check (status in ('pending','archived','failed')),
  last_error text,
  archive_run_id uuid references public.archive_backup_runs(id) on delete set null,
  updated_at timestamptz not null default now(),
  unique (bucket_id, object_name)
